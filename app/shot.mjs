import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const d = await browser.newContext({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true })
const p1 = await d.newPage()
await p1.goto('http://localhost:4180/#/', { waitUntil: 'networkidle', timeout: 30000 })
await p1.waitForTimeout(4000)
await p1.screenshot({ path: '/tmp/saas-board.png' })
await p1.goto('http://localhost:4180/#/launch', { waitUntil: 'networkidle' })
await p1.waitForTimeout(1200)
await p1.screenshot({ path: '/tmp/saas-launch.png' })
const tok = await p1.evaluate(() => '0x8960bE42d9dEEb973AB6e2DCa837B3bD78c9d5bD')
await p1.goto(`http://localhost:4180/#/t/${tok}`, { waitUntil: 'networkidle' })
await p1.waitForTimeout(3500)
await p1.screenshot({ path: '/tmp/saas-token.png' })
const m = await browser.newContext({ ...devices['iPhone 13'], ignoreHTTPSErrors: true })
const p2 = await m.newPage()
await p2.goto('http://localhost:4180/#/', { waitUntil: 'networkidle', timeout: 30000 })
await p2.waitForTimeout(4000)
await p2.screenshot({ path: '/tmp/saas-mobile.png' })
await browser.close()
console.log('shots done')
