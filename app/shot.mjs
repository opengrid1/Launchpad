import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const d = await browser.newContext({ viewport: { width: 1440, height: 1100 }, ignoreHTTPSErrors: true })
const p = await d.newPage()
await p.goto('http://localhost:4203/#/', { waitUntil: 'domcontentloaded', timeout: 30000 })
await p.waitForTimeout(8000)
await p.screenshot({ path: '/tmp/meteora-d.png' })
const m = await browser.newContext({ ...devices['iPhone 13'], ignoreHTTPSErrors: true })
const pm = await m.newPage()
await pm.goto('http://localhost:4203/#/', { waitUntil: 'domcontentloaded', timeout: 30000 })
await pm.waitForTimeout(8000)
await pm.screenshot({ path: '/tmp/meteora-m.png', fullPage: true })
await browser.close()
console.log('done')
